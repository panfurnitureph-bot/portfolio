/* Builds src/store/store.css: the Pan Furnitures storefront stylesheet (Tailwind v3 with the site's own
   theme — cream / ink / cognac palette, Inter + Cormorant, fadeIn keyframes) compiled with every utility
   scoped under `.store-root`, so it can coexist with the portfolio's, the Pan demo's and the console's CSS.
   Run after copying new files into src/store/real (npm run store:css). */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import postcss from 'postcss'
import tailwind from 'tailwindcss3'
import autoprefixer from 'autoprefixer'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const real = path.join(root, 'src/store/real')
const SCOPE = '.store-root'

/* Mirrors the site's tailwind.config.ts. */
const config = {
  important: SCOPE,
  corePlugins: { preflight: false },
  content: [path.join(real, '**/*.{ts,tsx}').replace(/\\/g, '/'), path.join(root, 'src/store/*.tsx').replace(/\\/g, '/')],
  theme: {
    extend: {
      colors: {
        cream: '#FAF7F2', ink: '#1A1A1A', cognac: '#B87333', sand: '#E8DFD3', stone: '#6B6560',
        olive: '#4A4123', espresso: '#33261C', linen: '#F6EFE7',
        /* PAN brand (from the logo): deep brown ground, gold ring and lettering */
        brown: '#5B4A2F', brownDeep: '#3E3220', gold: '#E2C27A', goldDeep: '#B08A3E', goldSoft: '#F3E7C9',
      },
      fontFamily: {
        sans: ['var(--font-inter)', 'Helvetica', 'Arial', 'sans-serif'],
        /* display face: the site kept the `cormorant` name but moved to Bricolage Grotesque */
        cormorant: ['var(--font-cormorant)', 'Segoe UI', 'Helvetica', 'sans-serif'],
      },
      keyframes: { fadeIn: { '0%': { opacity: '0' }, '100%': { opacity: '1' } } },
      animation: { fadeIn: 'fadeIn 1.2s ease-in-out' },
      letterSpacing: { widest2: '0.2em' },
    },
  },
  plugins: [],
}

/* Scoped stand-in for Tailwind's preflight (the bits the site relies on). */
const preflight = `
${SCOPE}, ${SCOPE} *, ${SCOPE} ::before, ${SCOPE} ::after { box-sizing: border-box; border-width: 0; border-style: solid; border-color: #E8DFD3; }
${SCOPE} { line-height: 1.5; -webkit-text-size-adjust: 100%; font-family: var(--font-inter), Helvetica, Arial, sans-serif; }
${SCOPE} h1, ${SCOPE} h2, ${SCOPE} h3, ${SCOPE} h4, ${SCOPE} h5, ${SCOPE} h6, ${SCOPE} p, ${SCOPE} figure, ${SCOPE} blockquote, ${SCOPE} pre, ${SCOPE} dl, ${SCOPE} dd { margin: 0; }
${SCOPE} h1, ${SCOPE} h2, ${SCOPE} h3, ${SCOPE} h4, ${SCOPE} h5, ${SCOPE} h6 { font-size: inherit; font-weight: inherit; }
${SCOPE} ol, ${SCOPE} ul, ${SCOPE} menu { list-style: none; margin: 0; padding: 0; }
${SCOPE} img, ${SCOPE} svg, ${SCOPE} video, ${SCOPE} canvas, ${SCOPE} iframe { display: block; vertical-align: middle; }
${SCOPE} img, ${SCOPE} video { max-width: 100%; height: auto; }
${SCOPE} button, ${SCOPE} input, ${SCOPE} optgroup, ${SCOPE} select, ${SCOPE} textarea { font-family: inherit; font-size: 100%; font-weight: inherit; line-height: inherit; color: inherit; margin: 0; padding: 0; }
${SCOPE} button, ${SCOPE} [role="button"] { cursor: pointer; }
${SCOPE} button, ${SCOPE} select { text-transform: none; }
${SCOPE} button, ${SCOPE} [type='button'], ${SCOPE} [type='reset'], ${SCOPE} [type='submit'] { -webkit-appearance: button; background-color: transparent; background-image: none; }
${SCOPE} table { text-indent: 0; border-color: inherit; border-collapse: collapse; }
${SCOPE} a { color: inherit; text-decoration: inherit; }
${SCOPE} hr { height: 0; color: inherit; border-top-width: 1px; }
${SCOPE} input::placeholder, ${SCOPE} textarea::placeholder { opacity: 1; color: #9ca3af; }
${SCOPE} :disabled { cursor: default; }
${SCOPE} [hidden] { display: none; }
${SCOPE} b, ${SCOPE} strong { font-weight: bolder; }
${SCOPE} code, ${SCOPE} kbd, ${SCOPE} samp, ${SCOPE} pre { font-family: ui-monospace, SFMono-Regular, Menlo, Monaco, Consolas, monospace; font-size: 1em; }
${SCOPE} small { font-size: 80%; }
${SCOPE} sub, ${SCOPE} sup { font-size: 75%; line-height: 0; position: relative; vertical-align: baseline; }
${SCOPE} textarea { resize: vertical; }
${SCOPE} fieldset, ${SCOPE} legend { margin: 0; padding: 0; }
${SCOPE} input[type='range'] { -webkit-appearance: none; appearance: none; background: transparent; }
`

/* Source: the site's app/globals.css (its body rule becomes the scope root). */
let src = fs.readFileSync(path.join(real, 'globals.css'), 'utf8')
src = src.replace(/@tailwind (base|components|utilities);\s*/g, '').replace(/(^|\n)\s*body\s*\{/g, `$1${SCOPE} {`)

const input = `@tailwind base;\n@tailwind components;\n@tailwind utilities;\n@layer base {\n${preflight}\n}\n` + src

const out = await postcss([tailwind(config), autoprefixer]).process(input, { from: path.join(real, 'globals.css'), to: path.join(root, 'src/store/store.css') })
const header = `/* GENERATED by tools/build-store-css.mjs — do not edit. Pan Furnitures storefront styles scoped to ${SCOPE}. */\n`
fs.writeFileSync(path.join(root, 'src/store/store.css'), header + out.css)
console.log('store.css written:', (out.css.length / 1024).toFixed(0), 'KB')
